-- 1. ตารางข้อมูลผู้ใช้งานหลัก (USERS)
CREATE TABLE dbo.USERS (
    USR_ID          INT IDENTITY(1,1) NOT NULL,
    USR_LOGIN       NVARCHAR(50)      NOT NULL,
    USR_NAME        NVARCHAR(150)     NOT NULL,
    USR_EMAIL       NVARCHAR(150)     NOT NULL,
    USR_REGISTDATE  DATETIME          NOT NULL CONSTRAINT DF_USERS_REGISTDATE DEFAULT (GETDATE()),
    USR_RESETDATE   DATETIME          NULL,
    USR_PIC         INT               NULL,
    USR_PIC_EMAIL   NVARCHAR(150)     NULL,
    USR_STATUS      TINYINT           NOT NULL CONSTRAINT DF_USERS_STATUS DEFAULT (1),
    GROUPS          INT               NOT NULL CONSTRAINT DF_USERS_GROUPS DEFAULT (16),
    VENDORS         INT               NULL,
    PROD_ID         NVARCHAR(50)      NULL,
    USR_PDPA        TINYINT           NOT NULL CONSTRAINT DF_USERS_PDPA DEFAULT (0),
    USR_LASTLOGIN   DATETIME          NULL,
    USR_LASTUPDATE  DATETIME          NULL     CONSTRAINT DF_USERS_LASTUPDATE DEFAULT (GETDATE()),

    CONSTRAINT PK_USERS PRIMARY KEY CLUSTERED (USR_ID ASC),
    CONSTRAINT UQ_USERS_LOGIN UNIQUE (USR_LOGIN),
    CONSTRAINT FK_USERS_PIC FOREIGN KEY (USR_PIC) REFERENCES dbo.USERS (USR_ID)
);

CREATE NONCLUSTERED INDEX IX_USERS_EMAIL ON dbo.USERS (USR_EMAIL);
CREATE NONCLUSTERED INDEX IX_USERS_VENDORS ON dbo.USERS (VENDORS);
CREATE NONCLUSTERED INDEX IX_USERS_GROUPS_STATUS ON dbo.USERS (GROUPS, USR_STATUS);

-- 2. ตารางรหัสผ่านผู้ใช้งาน (USERS_PASSWORD)
CREATE TABLE dbo.USERS_PASSWORD (
    USERS           INT          NOT NULL,
    PWD_CURRENT     VARCHAR(128) NOT NULL,
    PWD_PREVIOUS    VARCHAR(128) NULL,
    PWD_UPDATEDATE  DATETIME     NULL CONSTRAINT DF_USERS_PWD_UPDATEDATE DEFAULT (GETDATE()),

    CONSTRAINT PK_USERS_PASSWORD PRIMARY KEY CLUSTERED (USERS ASC),
    CONSTRAINT FK_USERS_PASSWORD_USERS FOREIGN KEY (USERS) REFERENCES dbo.USERS (USR_ID) ON DELETE CASCADE
);