CREATE TABLE dbo.ACCESS_LOG (
    LOG_ID       BIGINT         IDENTITY(1,1) NOT NULL,
    LOG_HOST     NVARCHAR(100)  NULL,
    LOG_PROGRAM  NVARCHAR(100)  NOT NULL,               -- เช่น LOGIN, LOGOUT, RESET_PASSWORD
    LOG_USER     NVARCHAR(100)  NOT NULL,               -- อ้างอิง USERS.USR_LOGIN
    LOG_IP       NVARCHAR(45)   NOT NULL,               -- รองรับทั้ง IPv4 และ IPv6
    LOG_DATE     DATETIME2(0)   NOT NULL CONSTRAINT DF_ACCESS_LOG_DATE DEFAULT (SYSDATETIME()),
    LOG_STATUS   TINYINT        NOT NULL,               -- 1 = Successful, 0 = Failure
    LOG_REASON   NVARCHAR(500)  NULL,                   -- เหตุผลกรณี Failure หรือหมายเหตุเพิ่มเติม

    CONSTRAINT PK_ACCESS_LOG PRIMARY KEY CLUSTERED (LOG_ID DESC)
);
GO

-- Index สำหรับดึง log ย้อนหลัง 30 วัน (LOG_DATE >= GETDATE()-30) และการค้นหาตามผู้ใช้/IP
CREATE NONCLUSTERED INDEX IX_ACCESS_LOG_DATE
    ON dbo.ACCESS_LOG (LOG_DATE DESC)
    INCLUDE (LOG_USER, LOG_IP, LOG_PROGRAM, LOG_STATUS);
GO

CREATE NONCLUSTERED INDEX IX_ACCESS_LOG_USER_DATE
    ON dbo.ACCESS_LOG (LOG_USER, LOG_DATE DESC);
GO

CREATE NONCLUSTERED INDEX IX_ACCESS_LOG_IP_DATE
    ON dbo.ACCESS_LOG (LOG_IP, LOG_DATE DESC);
GO

ALTER TABLE dbo.ACCESS_LOG ADD
    LOG_SESSION_ID  NVARCHAR(100)  NULL,   -- X-Session-ID
    LOG_USER_AGENT  NVARCHAR(500)  NULL,   -- Browser / Client User-Agent
    LOG_METHOD      NVARCHAR(10)   NULL,   -- GET, POST, PUT, DELETE
    LOG_PATH        NVARCHAR(255)  NULL;   -- Endpoint เช่น /api/v1/auth/login
GO