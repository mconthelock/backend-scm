-- 3. ตารางงวดส่งมอบย่อย (Separate Shipment Schedules)
CREATE TABLE ORDERS_SHIPMENT_SCHEDULE (
    ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PO_ITEM_ID INT NOT NULL,
    SPLIT_SEQ INT NOT NULL DEFAULT 1,
    SCHEDULED_QTY DECIMAL(18, 4) NOT NULL DEFAULT 0.0000,
    PROMISED_SHIP_DATE DATE NOT NULL,
    ESTIMATED_ARRIVAL_DATE DATE NOT NULL,
    VENDOR_REMARKS NVARCHAR(255) NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    ASN_NO VARCHAR(50) NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT GETDATE(),
    UPDATED_AT DATETIME NULL DEFAULT GETDATE()
);

CREATE NONCLUSTERED INDEX IDX_SCHED_PO_ITEM ON ORDERS_SHIPMENT_SCHEDULE (PO_ITEM_ID);
CREATE NONCLUSTERED INDEX IDX_SCHED_STATUS ON ORDERS_SHIPMENT_SCHEDULE (STATUS);
CREATE NONCLUSTERED INDEX IDX_SCHED_ASN_NO ON ORDERS_SHIPMENT_SCHEDULE (ASN_NO);

-- 4. ตารางใบแจ้งการจัดส่งล่วงหน้า (Advance Shipping Notices: ASN)
CREATE TABLE ADVANCE_SHIPPING_NOTICES (
    ASN_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ASN_NO VARCHAR(50) NOT NULL UNIQUE,
    PO_ID INT NOT NULL,
    BARCODE_TOKEN VARCHAR(100) NOT NULL,
    CARRIER_NAME NVARCHAR(100) NOT NULL,
    TRUCK_PLATE_NO NVARCHAR(50) NOT NULL,
    DRIVER_NAME NVARCHAR(100) NOT NULL,
    DRIVER_PHONE VARCHAR(50) NOT NULL,
    DISPATCH_TIME DATETIME NOT NULL,
    ESTIMATED_ARRIVAL_TIME DATETIME NOT NULL,
    ACTUAL_ARRIVAL_TIME DATETIME NULL,
    RECEIVING_DOCK NVARCHAR(50) NOT NULL DEFAULT 'Gate B Dock',
    STATUS VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    RECEIVE_TIME DATETIME NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE NONCLUSTERED INDEX IDX_ASN_PO_ID ON ADVANCE_SHIPPING_NOTICES (PO_ID);
CREATE NONCLUSTERED INDEX IDX_ASN_STATUS ON ADVANCE_SHIPPING_NOTICES (STATUS);

-- 5. ตารางรายการสินค้าใน ASN (ASN Items)
CREATE TABLE ASN_ITEMS (
    ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ASN_NO VARCHAR(50) NOT NULL,
    PO_ITEM_ID INT NOT NULL,
    SHIPMENT_SCHEDULE_ID INT NULL,
    DISPATCH_QTY DECIMAL(18, 4) NOT NULL DEFAULT 0.0000,
    RECEIVED_QTY DECIMAL(18, 4) NOT NULL DEFAULT 0.0000,
    REJECTED_QTY DECIMAL(18, 4) NOT NULL DEFAULT 0.0000,
    LOT_BATCH_NO VARCHAR(50) NULL,
    PACKAGE_CRATE_NO VARCHAR(50) NULL,
    QA_STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    CREATED_AT DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE NONCLUSTERED INDEX IDX_ASN_ITEMS_ASN_NO ON ASN_ITEMS (ASN_NO);
CREATE NONCLUSTERED INDEX IDX_ASN_ITEMS_PO_ITEM_ID ON ASN_ITEMS (PO_ITEM_ID);

-- 6. ตารางบันทึกกิจกรรม (Audit Trail: PO_AUDIT_LOGS - Insert-Only)
CREATE TABLE PO_AUDIT_LOGS (
    ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    PO_ID INT NOT NULL,
    WORKFLOW_EVENT NVARCHAR(150) NOT NULL,
    ACTION_CODE VARCHAR(50) NOT NULL,
    ACTOR_NAME NVARCHAR(150) NOT NULL,
    ACTOR_ORG NVARCHAR(150) NULL,
    IP_ADDRESS VARCHAR(50) NOT NULL,
    SESSION_ID VARCHAR(100) NULL,
    DETAILS NVARCHAR(MAX) NULL,
    STATUS VARCHAR(50) NULL,
    HASH VARCHAR(128) NULL,
    CREATED_AT DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE NONCLUSTERED INDEX IDX_AUDIT_PO_ID ON PO_AUDIT_LOGS (PO_ID);
CREATE NONCLUSTERED INDEX IDX_AUDIT_CREATED_AT ON PO_AUDIT_LOGS (CREATED_AT);
