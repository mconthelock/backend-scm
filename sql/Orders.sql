-- 3. ตารางแยกงวดส่งมอบ (PO_ITEM_SHIPMENT_SCHEDULES ต่อ Line Item)
CREATE TABLE ORDERS_SHIPMENTS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    PO_ITEM_ID BIGINT NOT NULL,
    SPLIT_SEQ INT NOT NULL DEFAULT 1,
    SCHEDULED_QTY DECIMAL(12, 4) NOT NULL,
    PROMISED_SHIP_DATE DATE NOT NULL,
    ESTIMATED_ARRIVAL_DATE DATE NOT NULL,
    STATUS ENUM('SCHEDULED', 'ASN_LINKED', 'PARTIAL_DISPATCHED', 'COMPLETED', 'CANCELLED') NOT NULL DEFAULT 'SCHEDULED',
    VENDOR_REMARKS VARCHAR(255) NULL,
    CREATED_BY BIGINT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (PO_ITEM_ID) REFERENCES PO_ITEMS(ID) ON DELETE CASCADE,
    INDEX IDX_PO_ITEM_SPLIT (PO_ITEM_ID, SPLIT_SEQ)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. ตารางใบแจ้งการจัดส่งล่วงหน้า (ADVANCE_SHIPPING_NOTICES: ASN)
CREATE TABLE ORDERS_ASN (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ASN_NO VARCHAR(32) NOT NULL UNIQUE,
    PO_ID BIGINT NOT NULL,
    VENDOR_ID BIGINT NOT NULL,
    CARRIER_NAME VARCHAR(100) NOT NULL,
    TRUCK_PLATE_NO VARCHAR(50) NOT NULL,
    DRIVER_NAME VARCHAR(100) NULL,
    DRIVER_PHONE VARCHAR(30) NULL,
    DISPATCH_TIME DATETIME NOT NULL,
    ESTIMATED_ARRIVAL_TIME DATETIME NOT NULL,
    ACTUAL_ARRIVAL_TIME DATETIME NULL,
    RECEIVING_DOCK VARCHAR(50) NOT NULL DEFAULT 'Gate B Dock',
    BARCODE_TOKEN VARCHAR(64) NOT NULL UNIQUE,
    COA_FILE_PATH VARCHAR(255) NULL,
    STATUS ENUM('CREATED', 'IN_TRANSIT', 'GATE_ARRIVED', 'QA_INSPECTION', 'COMPLETED', 'REJECTED') NOT NULL DEFAULT 'CREATED',
    CREATED_BY BIGINT NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (PO_ID) REFERENCES PURCHASE_ORDERS(ID) ON DELETE CASCADE,
    INDEX IDX_ASN_VENDOR (VENDOR_ID),
    INDEX IDX_ASN_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. ตารางรายการสิ่งของในแต่ละใบจัดส่ง (ASN_ITEMS)
CREATE TABLE ORDERS_ASN_ITEMS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ASN_ID BIGINT NOT NULL,
    PO_ITEM_ID BIGINT NOT NULL,
    SHIPMENT_SCHEDULE_ID BIGINT NULL,
    DISPATCH_QTY DECIMAL(12, 4) NOT NULL,
    RECEIVED_QTY DECIMAL(12, 4) NOT NULL DEFAULT 0.0000,
    REJECTED_QTY DECIMAL(12, 4) NOT NULL DEFAULT 0.0000,
    LOT_BATCH_NO VARCHAR(60) NULL,
    PACKAGE_CRATE_NO VARCHAR(50) NULL,
    QA_INSPECTION_STATUS ENUM('PENDING', 'PASSED', 'REJECTED') NOT NULL DEFAULT 'PENDING',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ASN_ID) REFERENCES ADVANCE_SHIPPING_NOTICES(ID) ON DELETE CASCADE,
    FOREIGN KEY (PO_ITEM_ID) REFERENCES PO_ITEMS(ID) ON DELETE CASCADE,
    FOREIGN KEY (SHIPMENT_SCHEDULE_ID) REFERENCES PO_ITEM_SHIPMENT_SCHEDULES(ID) ON DELETE SET NULL,
    INDEX IDX_ASN_PO_ITEM (ASN_ID, PO_ITEM_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. ตารางบันทึกประวัติการกระทำและตรวจรับ (PO_AUDIT_LOGS)
CREATE TABLE ORDERS_AUDIT_LOGS (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    PO_ID BIGINT NOT NULL,
    ACTION_CODE VARCHAR(40) NOT NULL,
    WORKFLOW_EVENT VARCHAR(100) NOT NULL,
    ACTOR_TYPE ENUM('AMEC_BUYER', 'AMEC_QC', 'SUPPLIER', 'SYSTEM') NOT NULL,
    ACTOR_USER_ID BIGINT NOT NULL,
    ACTOR_NAME VARCHAR(100) NOT NULL,
    ACTOR_ORG VARCHAR(120) NOT NULL,
    IP_ADDRESS VARCHAR(45) NOT NULL,
    SESSION_ID VARCHAR(64) NULL,
    ACTION_DETAILS TEXT NULL,
    VERIFICATION_HASH VARCHAR(64) NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (PO_ID) REFERENCES PURCHASE_ORDERS(ID) ON DELETE CASCADE,
    INDEX IDX_LOG_PO_ACTION (PO_ID, ACTION_CODE),
    INDEX IDX_LOG_CREATED_AT (CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;