-- สร้างตาราง ORDERS สำหรับ Microsoft SQL Server
CREATE TABLE ORDERS (
    ORD_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    ORD_PONO VARCHAR(32) NOT NULL,
    ORD_REVISION INT NOT NULL DEFAULT 0,
    ORD_DOCREV INT NOT NULL DEFAULT 1,
    ORD_TYPE INT NOT NULL DEFAULT 1,
    ORD_PODATE DATETIME NOT NULL,
    ORD_REFNO VARCHAR(50) NULL,
    ORD_SHIPTO VARCHAR(100) NULL,
    ORD_SHIPBY VARCHAR(50) NULL,
    ORD_CURRENCY VARCHAR(10) NOT NULL DEFAULT 'THB',
    ORD_PAYMENT VARCHAR(50) NULL,
    ORD_TRADE VARCHAR(50) NULL,
    VENDORCODE VARCHAR(20) NOT NULL,
    VENDOR INT NOT NULL,
    ADDR INT NULL,
    BUYERCODE VARCHAR(20) NULL,
    BUYER VARCHAR(20) NULL,
    ORD_AMOUNT DECIMAL(18, 4) NULL DEFAULT 0.0000,
    ORD_STATUS INT NOT NULL DEFAULT 1,
    ORD_BUYERCOMMENT NVARCHAR(MAX) NULL,
    ORD_VENDORCOMMENT NVARCHAR(MAX) NULL,
    ORD_CLOSED TINYINT NOT NULL DEFAULT 0,
    ORD_LATEST TINYINT NOT NULL DEFAULT 1,
    ORD_LASTUPDATE DATETIME NOT NULL DEFAULT GETDATE(),

    -- Constraints & Indexes
    CONSTRAINT UQ_ORDERS_PONO_REV UNIQUE (ORD_PONO, ORD_DOCREV)
);

-- ดัชนีเพื่อเพิ่มประสิทธิภาพการค้นหาตามที่เรียกใช้ใน Model/Controllers
CREATE NONCLUSTERED INDEX IDX_ORDERS_PONO ON ORDERS (ORD_PONO);
CREATE NONCLUSTERED INDEX IDX_ORDERS_VENDOR ON ORDERS (VENDOR);
CREATE NONCLUSTERED INDEX IDX_ORDERS_STATUS ON ORDERS (ORD_STATUS);
CREATE NONCLUSTERED INDEX IDX_ORDERS_PODATE ON ORDERS (ORD_PODATE);


-- สร้างตาราง ORDER_DETAIL สำหรับ Microsoft SQL Server
